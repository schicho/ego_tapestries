def conditional_sequence(condition: str, components: list):
    return rvt.sequence(
        id=condition, conditional=True, order="fixed", components=components
    )


def conditional_sequence_of_sequence(condition: str, sequence):
    """Like conditional_sequence, for a sequence (sequences are added with +=)."""
    conditional = rvt.sequence(id=condition, conditional=True, order="fixed", components=[])
    conditional += sequence
    return conditional


