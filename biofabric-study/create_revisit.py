def conditional_sequence(condition: str, components: list):
    return rvt.sequence(
        id=condition, conditional=True, order="fixed", components=components
    )


def conditional_sequence_of_sequence(condition: str, sequence):
    """Like conditional_sequence, for a sequence (sequences are added with +=)."""
    conditional = rvt.sequence(id=condition, conditional=True, order="fixed", components=[])
    conditional += sequence
    return conditional


def generate_intro_sequence():

    # Participants can only continue if the link of the study contains a valid condition. The consent
    # page checks this itself, and shows a warning instead of the consent form if it does not.
    consent = rvt.component(
        component_name__="consent",
        type="website",
        path="biofabric-study/assets/consent.html",
        nextButtonText="I Agree",
        response=[
            rvt.response(
                type="reactive",
                id="conditionCheck",
                prompt="",
                required=True,
                location="belowStimulus",
                showList=False,  # the page shows its own message
            )
        ],
    )

    intro_introduction = rvt.component(
        component_name__="intro_introduction",
        type="markdown",
        path="biofabric-study/assets/introduction.md",
    )

    intro_tutorial = rvt.component(
        component_name__="intro_tutorial",
        type="markdown",
        path="biofabric-study/assets/tutorial.md",
    )

    intro_graph_terminology_biofabric = rvt.component(
        component_name__="intro_graph_terminology_biofabric",
        type="markdown",
        path="biofabric-study/assets/graph_terminology_biofabric.md",
        helpTextPath="biofabric-study/assets/help/tutorial_normal.md",
    )

    intro_graph_terminology_biofabric_collapsed = rvt.component(
        component_name__="intro_graph_terminology_biofabric_collapsed",
        type="markdown",
        path="biofabric-study/assets/graph_terminology_biofabric_collapsed.md",
        helpTextPath="biofabric-study/assets/help/tutorial_collapsed.md",
    )

    # a brief explanation of the NASA-TLX questionnaire that follows each group of questions
    intro_tlx_tutorial = rvt.component(
        component_name__="intro_tlx_tutorial",
        type="markdown",
        path="biofabric-study/assets/tlx_tutorial.md",
        helpTextPath="biofabric-study/assets/help/tlx.md",
    )

    intro_sequence = rvt.sequence(
        order="fixed",
        components=[consent, intro_introduction, intro_tutorial],
    )
    # sequences are added with += (a sequence can not be passed in the components list)
    intro_sequence += conditional_sequence(
        CONDITION_NORMAL, [intro_graph_terminology_biofabric]
    )
    intro_sequence += conditional_sequence(
        CONDITION_COLLAPSED, [intro_graph_terminology_biofabric_collapsed]
    )
    intro_sequence += rvt.sequence(order="fixed", components=[intro_tlx_tutorial])
    return intro_sequence


